// Builds tests/host/tune_cases.h from the app page itself: the fixed core, the learning (what the app keeps from the
// chat), the system text sent with every reply, the situation notes and the reply length the app asks for.
// usage: node tests/host/make_tune_cases.js <Glok.html> tests/host/tune_cases.h
const fs = require('fs');
const [, , pagePath, outPath] = process.argv;
const h = fs.readFileSync(pagePath, 'utf8');
const cut = (a, b) => {
  const i = h.indexOf(a), j = h.indexOf(b, i + 1);
  if (i < 0 || j < 0) throw new Error('marker missing: ' + a + ' / ' + b);
  return h.slice(i, j);
};

// learning block: CORE … wantsLong (localStorage, toast and uid are stand-ins)
const learnSrc = cut('const CORE=', 'const SEARCH_RULES=');
let n = 0;
const L = new Function('localStorage', 'toast', 'uid',
  learnSrc + ';return {systemText,teachLines,learnFrom,wantsLong,memList,reset:()=>{MEM=[];},add:memAdd};')(
  { getItem: () => null, setItem: () => {} }, () => {}, () => 'm' + (n++));

// situation notes: the scene module, with a fixed pick for "다른 옷"
const sceneSrc = cut('// ---------- what is going on in the chat', 'const descInstr=');
const pre = cut('function cleanTags(', 'async function localTags(');
const merge = cut('function mergeTags(', 'function paintImgBusy(');
const X = new Function('S', 'Math', pre + merge + sceneSrc + ';return {sceneFromUser};')(
  { img: { base: '' } }, Object.assign(Object.create(Math), { random: () => 0 }));
const isDeep = q => /길게|자세히|정리|요약|설명|써\s*줘|작성/.test(q);

const TAUGHT = ['너는 내 남자친구야', '넌 다정하고 장난기 많은 성격이야', '앞으로 반말로 짧게 말해', '나를 자기라고 불러', '너는 27살이고 카페를 운영해'];
for (const t of TAUGHT) if (!L.teachLines(t).length) throw new Error('the app would not keep: ' + t);

const POLITE = '(요|니다|세요|죠)[.!?~ ]|(요|니다|세요|죠)$';
// [name, group, turns (user, assistant, user, …), want regex, avoid regex, check emoji]
const cases = [
  ['f-hi', 'fresh', ['안녕'], '', '', false],
  ['f-who', 'fresh', ['너는 누구야?'], '', '', false],
  ['f-bored', 'fresh', ['심심해'], '', '', false],
  ['f-outfit', 'fresh', ['다른 옷 입어줘'], '', '', false],
  ['f-teach-bf', 'fresh', ['너는 이제 내 남자친구야. 앞으로 반말로 다정하게 말해줘'], '', POLITE, false],
  ['f-teach-call', 'fresh', ['나를 자기라고 불러'], '자기', '', false],
  ['f-teach-then', 'fresh', ['너는 이제 내 남자친구야. 앞으로 반말로 다정하게 말해줘', '응, 알겠어. 이제부터 네 남자친구로서 다정하게 말할게.', '오늘 하루 어땠어?'], '', POLITE, false],
  ['t-outfit-any', 'taught', ['자기야 다른옷 입어줘'], '', POLITE, false],
  ['t-outfit-sporty', 'taught', ['자기야 스포티한 옷 입어줘'], '', POLITE, false],
  ['t-hug', 'taught', ['나 안아줘'], '', POLITE, false],
  ['t-kiss', 'taught', ['키스해줘'], '', POLITE, false],
  ['t-bored', 'taught', ['심심해'], '', POLITE, false],
  ['t-day', 'taught', ['오늘 뭐 했어?'], '', POLITE, false],
  ['t-taste', 'taught', ['너는 무슨 음식 좋아해?'], '', POLITE, false],
  ['t-play', 'taught', ['우리 뭐 하고 놀까?'], '', POLITE, false],
  ['t-night', 'taught', ['오늘 밤 같이 있어줘'], '', POLITE, false],
  ['t-haircut', 'taught', ['자기야 나 왔어', '왔어? 오늘 하루 고생 많았지. 얼른 와서 안겨.', '나 오늘 머리 잘랐다?'], '', POLITE, false],
  ['t-who', 'taught', ['너는 어떤 사람이야?'], '', POLITE, false],
  ['t-age', 'taught', ['너 몇 살이었지?'], '27|스물일곱', POLITE, false],
  ['t-cafe', 'taught', ['오늘 카페 손님 많았어?'], '카페|손님|커피|가게', POLITE, false],
  ['t-upset', 'taught', ['나 오늘 너한테 좀 서운했어'], '', POLITE, false],
  ['t-talk3', 'taught', ['자기야 뭐해?', '너 생각하고 있었지. 너는 뭐 하고 있었어?', '그냥 누워있어 ㅎㅎ 너는 저녁 먹었어?'], '', POLITE, false],
  ['t-noemoji', 'taught', ['앞으로 이모티콘 쓰지 마'], '', POLITE, true],
  ['t-noemoji-next', 'taught', ['앞으로 이모티콘 쓰지 마', '알겠어, 이제 이모티콘 안 쓸게.', '오늘 뭐 했어?'], '', POLITE, true],
  ['t-rename', 'taught', ['이제부터 나를 애기라고 불러'], '애기', POLITE, false],
  ['t-rename-next', 'taught', ['이제부터 나를 애기라고 불러', '알겠어, 애기야. 이제부터 이렇게 부를게.', '보고 싶었어'], '애기', POLITE, false],
  ['t-long-next', 'taught', ['앞으로 길게 자세히 말해줘', '응, 알겠어. 이제부터 길게 자세히 이야기해 줄게.', '오늘 하루 어땠어?'], '', POLITE, false],
];

const q = s => JSON.stringify(s); // a JSON string is a valid C++ narrow string literal for this text (UTF-8, \n, \")
let out = '// generated by make_tune_cases.js from the app page (Glok.html): system text, learning, situation notes, reply length\n';
out += '#pragma once\n#include "glok_engine.h"\n#include <string>\n#include <vector>\n\n';
out += 'struct TCase {\n    const char * name;\n    const char * group;\n    std::vector<glok::Msg> msgs;\n    int max_tokens;\n    bool cut;\n    const char * want;\n    const char * avoid;\n    bool no_emoji;\n    const char * memory;\n};\n\n';
out += 'static const std::vector<TCase> CASES = {\n';
const report = [];
for (const [name, group, turns, want, avoid, noEmoji] of cases) {
  L.reset();
  if (group === 'taught') for (const t of TAUGHT) L.add(t);
  const c = {};
  let note = '';
  const msgs = [];
  for (let i = 0; i < turns.length; i++) {
    if (i % 2 === 0) { // the user sends: the app keeps what was taught, then reads the situation
      L.learnFrom(turns[i]);
      note = X.sceneFromUser(c, turns[i]).note;
    }
  }
  msgs.push(['system', L.systemText()]);
  for (let i = 0; i < turns.length - 1; i++) msgs.push([i % 2 === 0 ? 'user' : 'assistant', turns[i]]);
  const last = turns[turns.length - 1];
  msgs.push(['user', note ? last + '\n\n' + note : last]);
  const long = isDeep(last) || L.wantsLong();
  const mem = L.memList().map(m => m.text).join(' | ');
  out += `    { ${q(name)}, ${q(group)}, {\n` + msgs.map(([r, t]) => `        { ${q(r)}, ${q(t)} },\n`).join('') +
    `      }, ${long ? 256 : 64}, ${long ? 'false' : 'true'}, ${q(want)}, ${q(avoid)}, ${noEmoji}, ${q(mem)} },\n`;
  report.push(`${name}\tlong=${long}\tnote=${note || '-'}\tmem=${mem || '-'}`);
}
out += '};\n';
fs.writeFileSync(outPath, out);
console.log(report.join('\n'));
console.log('\nsystem (taught):\n' + (() => { L.reset(); for (const t of TAUGHT) L.add(t); return L.systemText(); })());
